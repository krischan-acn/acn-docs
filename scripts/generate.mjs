// Generates the reference pages under docs/reference/generated/ straight from
// the code, so they cannot drift from it.
//
// It reads a git ref (not the working tree), so the output describes what is
// committed on that branch regardless of what happens to be checked out.
//
//   npm run gen
//   NEWSROOM_DIR=../newsroom-main NEWSROOM_REF=main ADMIN_DIR=../acn-admin ADMIN_REF=master npm run gen

import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = resolve(root, 'docs/reference/generated')

const repos = {
  newsroom: {
    name: 'Newsroom',
    dir: resolve(root, process.env.NEWSROOM_DIR ?? '../newsroom-main'),
    ref: process.env.NEWSROOM_REF ?? 'main',
    github: 'https://github.com/krischan-acn/newsroom',
  },
  admin: {
    name: 'Admin',
    dir: resolve(root, process.env.ADMIN_DIR ?? '../acn-admin'),
    ref: process.env.ADMIN_REF ?? 'feat/api-write-wiring',
    github: 'https://github.com/s-ging/acn-admin',
  },
}

const git = (repo, ...args) =>
  execFileSync('git', ['-C', repo.dir, ...args], { encoding: 'utf8', maxBuffer: 64 << 20 })

function load(repo) {
  const sha = git(repo, 'rev-parse', '--short', repo.ref).trim()
  const date = git(repo, 'log', '-1', '--format=%cs', repo.ref).trim()
  const files = git(repo, 'ls-tree', '-r', '--name-only', repo.ref)
    .split('\n')
    .filter((f) => /^src\/.*\.(ts|tsx|js|jsx|mjs)$/.test(f) && !/\.test\.|__tests__/.test(f))
  // One `git cat-file --batch` call for every file; spawning git per file is very slow on Windows.
  const blobs = new Map()
  const out = execFileSync('git', ['-C', repo.dir, 'cat-file', '--batch'], {
    input: files.map((f) => `${repo.ref}:${f}`).join('\n') + '\n', maxBuffer: 256 << 20,
  })
  let pos = 0
  for (const f of files) {
    const nl = out.indexOf(10, pos)
    const size = Number(out.subarray(pos, nl).toString().split(' ')[2])
    blobs.set(f, out.subarray(nl + 1, nl + 1 + size).toString('utf8'))
    pos = nl + 1 + size + 1
  }
  const read = (f) => blobs.get(f) ?? git(repo, 'show', `${repo.ref}:${f}`)
  return { ...repo, sha, date, files, read }
}

const stamp = (r) =>
  `> Generated by \`npm run gen\` from **${r.name}** \`${r.ref}\` at \`${r.sha}\` (last commit ${r.date}). ` +
  `Do not edit by hand: change the code, then run the generator again.\n`

const link = (r, file, line) => `[${file}${line ? `:${line}` : ''}](${r.github}/blob/${r.sha}/${file}${line ? `#L${line}` : ''})`

/** Every match of `re` in every file, as { key, file, line }. */
function scan(r, re, files = r.files) {
  const hits = []
  for (const file of files) {
    const lines = r.read(file).split('\n')
    lines.forEach((text, i) => {
      for (const m of text.matchAll(re)) hits.push({ key: m[1], file, line: i + 1 })
    })
  }
  return hits
}

function group(hits) {
  const map = new Map()
  for (const h of hits) {
    if (!map.has(h.key)) map.set(h.key, [])
    map.get(h.key).push(h)
  }
  return [...map.entries()].sort(([a], [b]) => a.localeCompare(b))
}

// ── Environment variables ──────────────────────────────────────────────────

function envPage(r) {
  const hits = [
    ...scan(r, /process\.env\.([A-Z0-9_]+)/g),
    ...scan(r, /import\.meta\.env\.([A-Z0-9_]+)/g),
  ]
  const rows = group(hits).map(([key, where]) =>
    `| \`${key}\` | ${where.slice(0, 4).map((h) => link(r, h.file, h.line)).join('<br>')}${where.length > 4 ? `<br>…and ${where.length - 4} more` : ''} |`)
  return `| Variable | Read at |\n| --- | --- |\n${rows.join('\n')}\n`
}

// ── API endpoints ──────────────────────────────────────────────────────────

function endpointsPage(r) {
  const hits = scan(r, /['"`](\/api\/[A-Za-z0-9_/{}$.\-]*)/g)
    .map((h) => ({ ...h, key: h.key.replace(/\$\{[^}]*\}?|\{[A-Za-z]+\}/g, '{…}').replace(/\/$/, '') }))
    // the app's own route handlers are listed under routes, not here
    .filter((h) => !/^\/api\/(ab|og|press-release|company-articles)\b/.test(h.key))
  const rows = group(hits).map(([key, where]) =>
    `| \`${key}\` | ${[...new Set(where.map((h) => h.file))].slice(0, 3).map((f) => link(r, f)).join('<br>')} |`)
  const hosts = group(scan(r, /(https:\/\/[a-z0-9.-]*acnnewswire\.com)/g))
    .map(([key, where]) => `- \`${key}\`: ${[...new Set(where.map((h) => h.file))].slice(0, 3).map((f) => link(r, f)).join(', ')}`)
  return `### Hosts referenced\n\n${hosts.join('\n')}\n\n### Paths\n\n| Path | Called from |\n| --- | --- |\n${rows.join('\n')}\n`
}

// ── Routes ─────────────────────────────────────────────────────────────────

function newsroomRoutes(r) {
  const rows = r.files
    .filter((f) => /^src\/app\/.*\/?(page|route)\.(tsx|ts)$/.test(f))
    .map((f) => {
      const kind = /route\.tsx?$/.test(f) ? 'API / handler' : 'Page'
      const url = '/' + f.replace(/^src\/app\/?/, '').replace(/\/?(page|route)\.tsx?$/, '')
        .split('/').filter((s) => s && !/^\(.*\)$/.test(s))
        .map((s) => s.replace(/^\[\.\.\.(.+)\]$/, '*$1').replace(/^\[(.+)\]$/, ':$1')).join('/')
      return { url, kind, f }
    })
    .sort((a, b) => a.kind.localeCompare(b.kind) || a.url.localeCompare(b.url))
  return `| URL | Type | File |\n| --- | --- | --- |\n${rows.map((x) => `| \`${x.url}\` | ${x.kind} | ${link(r, x.f)} |`).join('\n')}\n`
}

function adminRoutes(r) {
  const file = 'src/App.tsx'
  const src = r.read(file)
  const rows = []
  for (const m of src.matchAll(/path=["']([^"']+)["'][\s\S]*?element=\{<\s*(?:Suspense[^>]*>[\s\S]*?<\s*)?([A-Za-z]+)/g)) {
    const line = src.slice(0, m.index).split('\n').length
    rows.push(`| \`${m[1]}\` | \`${m[2]}\` | ${link(r, file, line)} |`)
  }
  return `| URL | Screen component | Defined at |\n| --- | --- | --- |\n${rows.join('\n')}\n`
}

// ── Components (newsroom tiers) ────────────────────────────────────────────

function newsroomComponents(r) {
  const comps = r.files.filter((f) => /^src\/components\/.*\.tsx$/.test(f))
  const tiers = { common: [], shared: [], features: [] }
  for (const f of comps) {
    const tier = f.split('/')[2]
    if (tiers[tier]) tiers[tier].push(f)
  }
  const section = (t, note) =>
    `### \`${t}/\`: ${note} (${tiers[t].length})\n\n${tiers[t].map((f) => `- ${link(r, f)}`).join('\n')}\n`
  return [
    'The tier rule (imports flow `features → shared → common`, never sideways between features) is in the newsroom\'s `BIBLE.md`. The full import graph, with every importer, is in [`COMPONENTS.toon`](' + r.github + '/blob/' + r.sha + '/COMPONENTS.toon).\n',
    section('common', 'on every page'),
    section('shared', 'used by two or more feature areas'),
    section('features', 'one feature area each'),
  ].join('\n')
}

// ── Taxonomy (sectors and industries) ──────────────────────────────────────

function taxonomyPage(r) {
  const src = r.read('src/lib/sectors.ts')
  const bySector = new Map()
  for (const m of src.matchAll(/sector_type:\s*'([^']+)',\s*sector_name:\s*'([^']+)'.*?name_ja:\s*(?:'([^']*)'|null)/g)) {
    if (!bySector.has(m[1])) bySector.set(m[1], [])
    bySector.get(m[1]).push({ industry: m[2], ja: m[3] ?? '' })
  }
  const total = [...bySector.values()].reduce((n, l) => n + l.length, 0)
  const out = [`**${bySector.size} sectors, ${total} industries.** Source: ${link(r, 'src/lib/sectors.ts')}, read through \`src/lib/taxonomy.ts\`.\n`]
  for (const [sector, list] of [...bySector.entries()].sort()) {
    out.push(`### ${sector} (${list.length})\n\n| Industry | Japanese |\n| --- | --- |\n${list.map((x) => `| ${x.industry} | ${x.ja} |`).join('\n')}\n`)
  }
  return out.join('\n')
}

// ── Write ──────────────────────────────────────────────────────────────────

const pages = []
function page(slug, title, intro, r, body) {
  pages.push({ slug, title })
  writeFileSync(resolve(outDir, `${slug}.md`), `# ${title}\n\n${stamp(r)}\n${intro}\n\n${body}`)
}

mkdirSync(outDir, { recursive: true })
const n = load(repos.newsroom)
const a = load(repos.admin)

page('newsroom-routes', 'Newsroom: every route', 'Every page and API route handler under `src/app`. `:id` is a single segment, `*segments` is a catch-all. What each page shows is explained in [the newsroom developer page](/build/newsroom).', n, newsroomRoutes(n))
page('newsroom-env', 'Newsroom: environment variables', 'Every variable the code actually reads. If a variable is set in Netlify or Vercel but missing here, it does nothing. Values are never written down; they live in the host dashboards.', n, envPage(n))
page('newsroom-endpoints', 'Newsroom: API endpoints called', 'Every ACN API path that appears in the newsroom source. `{…}` marks a value filled in at runtime.', n, endpointsPage(n))
page('newsroom-components', 'Newsroom: components by tier', '', n, newsroomComponents(n))
page('taxonomy', 'Sectors and industries', 'The classification ACN uses on press releases and companies. **Sector** is the broad group; **industry** is the narrower one inside it. In the old database the columns are one level off: `sector_type` is the sector and `sector_name` is the industry.', n, taxonomyPage(n))
page('admin-routes', 'Admin: every screen', 'Every URL in the admin app, from the router in `src/App.tsx`.', a, adminRoutes(a))
page('admin-env', 'Admin: environment variables', 'Every variable the code reads. `VITE_*` values are baked into the browser bundle at build time, so anyone can read them; never put a secret in one.', a, envPage(a))
page('admin-endpoints', 'Admin: API endpoints called', 'Every ACN API path in the admin source. In the browser these are all requested through the `/wire` proxy, never directly.', a, endpointsPage(a))

writeFileSync(resolve(outDir, 'index.md'),
  `# Generated reference\n\nThese pages are built from the code by \`npm run gen\` in this repo. Newsroom: \`${n.ref}\` at \`${n.sha}\`. Admin: \`${a.ref}\` at \`${a.sha}\`.\n\n${pages.map((p) => `- [${p.title}](./${p.slug})`).join('\n')}\n`)
console.log(`Wrote ${pages.length + 1} pages to docs/reference/generated (newsroom ${n.ref}@${n.sha}, admin ${a.ref}@${a.sha})`)
